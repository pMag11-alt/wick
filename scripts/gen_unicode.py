#!/usr/bin/env python3
"""Generate src/tokenizer/unicode_tables.rs from Python's Unicode database.

The tokenizer needs the \\p{L} and \\p{N} classes (for the pre-tokenizer
regexes) and the data for NFC normalization (Qwen's tokenizers normalize
their input): canonical decompositions, combining classes and the primary
composites.

    python3 scripts/gen_unicode.py > src/tokenizer/unicode_tables.rs
"""

import sys
import unicodedata

MAX = 0x110000


def ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        hit = pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def cat(cp):
    return unicodedata.category(chr(cp))


def is_hangul_syllable(cp):
    return 0xAC00 <= cp <= 0xD7A3


letters = ranges(lambda cp: cat(cp)[0] == "L")
numbers = ranges(lambda cp: cat(cp)[0] == "N")

# Non-zero canonical combining classes, as (first, last, class) runs.
ccc = []
for cp in range(MAX):
    c = unicodedata.combining(chr(cp))
    if c:
        if ccc and ccc[-1][1] == cp - 1 and ccc[-1][2] == c:
            ccc[-1] = (ccc[-1][0], cp, c)
        else:
            ccc.append((cp, cp, c))

# Canonical (not compatibility) decompositions, one or two code points.
decomp = []
for cp in range(MAX):
    if is_hangul_syllable(cp):
        continue
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        continue
    parts = [int(x, 16) for x in d.split()]
    assert 1 <= len(parts) <= 2, hex(cp)
    decomp.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))

# Primary composites: pairs that NFC recomposes (excludes singletons,
# composition exclusions and non-starter decompositions).
compose = []
for cp, a, b in decomp:
    if b and unicodedata.normalize("NFC", chr(cp)) == chr(cp) and unicodedata.combining(chr(a)) == 0:
        compose.append((a, b, cp))
compose.sort()


def emit_ranges(name, rs):
    print(f"pub static {name}: &[(u32, u32)] = &[")
    for i in range(0, len(rs), 6):
        print("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in rs[i:i + 6]))
    print("];")


print(f"// Generated by scripts/gen_unicode.py from Unicode {unicodedata.unidata_version}. Do not edit.")
print()
emit_ranges("LETTER", letters)
print()
emit_ranges("NUMBER", numbers)
print()
print("pub static COMBINING_CLASS: &[(u32, u32, u8)] = &[")
for i in range(0, len(ccc), 5):
    print("    " + " ".join(f"(0x{a:X}, 0x{b:X}, {c})," for a, b, c in ccc[i:i + 5]))
print("];")
print()
print("/// (code point, first, second); second is 0 for singleton decompositions.")
print("pub static DECOMPOSITION: &[(u32, u32, u32)] = &[")
for i in range(0, len(decomp), 4):
    print("    " + " ".join(f"(0x{a:X}, 0x{b:X}, 0x{c:X})," for a, b, c in decomp[i:i + 4]))
print("];")
print()
print("/// (first, second, composite), sorted for binary search.")
print("pub static COMPOSITION: &[(u32, u32, u32)] = &[")
for i in range(0, len(compose), 4):
    print("    " + " ".join(f"(0x{a:X}, 0x{b:X}, 0x{c:X})," for a, b, c in compose[i:i + 4]))
print("];")
print(f"// {len(letters)} letter ranges, {len(numbers)} number ranges, {len(ccc)} class runs, "
      f"{len(decomp)} decompositions, {len(compose)} compositions", file=sys.stderr)
